def source_fingerprints():
    return {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(ROOT.glob("*.py")) + sorted(ROOT.glob("*.cu"))}


def compare(cpu, gpu, tolerance):
    errors = {}
    for name in ("f", "rho", "ux", "uy"):
        actual = cp.asnumpy(getattr(gpu, name))
        expected = getattr(cpu, name)
        assert actual.dtype == expected.dtype == np.float64
        assert np.isfinite(actual).all(), name
        error = float(np.max(np.abs(actual - expected)))
        assert error <= tolerance, (name, error, tolerance)
        errors[name] = error
    residual = cpu._velocity_residual()
    if cpu.iteration:
        np.testing.assert_allclose(gpu.decision_residual, residual, atol=5e-12, rtol=5e-8)
    assert cpu.stop_reason == gpu.stop_reason, (cpu.stop_reason, gpu.stop_reason)
    assert cpu.iteration == gpu.iteration
    assert cpu._failure == gpu._failure
    errors["residual"] = abs(gpu.decision_residual - residual)
    errors["step"] = cpu.iteration
    errors["stop_reason"] = cpu.stop_reason
    if cpu.iteration:
        ramp = cpu.config.convergence.ramp_steps
        factor = min(1, cpu.iteration / ramp) if ramp else 1
        wall_u = cpu.config.boundaries["top"].ux * factor
        ux, uy = cp.asnumpy(gpu.ux), cp.asnumpy(gpu.uy)
        assert np.max(np.abs(ux[-1] - wall_u)) < 3e-14
        assert np.max(np.abs(ux[0])) < 3e-14
        assert np.max(np.abs(ux[:-1, [0, -1]])) < 3e-14
        assert np.max(np.abs(uy[[0, -1], :])) < 3e-14
        assert np.max(np.abs(uy[:, [0, -1]])) < 3e-14
    return errors


def trajectory(solver_type, grid, re, steps, random_state=False):
    config = make_config(grid=grid, re=re, max_iter=steps)
    if random_state:
        config.grid.NY = grid + 2
    cpu, gpu = CPUSolver(config), solver_type(config)
    if random_state:
        rng = np.random.default_rng(20260929)
        cpu.rho += rng.uniform(-1e-4, 1e-4, cpu.rho.shape)
        cpu.ux[:] = rng.uniform(-0.002, 0.002, cpu.ux.shape)
        cpu.uy[:] = rng.uniform(-0.002, 0.002, cpu.uy.shape)
        cpu.f = cpu.equilibrium(cpu.rho, cpu.ux, cpu.uy)
        cpu.f += rng.uniform(-1e-6, 1e-6, cpu.f.shape)
        cpu.update_macroscopic()
        gpu.load_state(f=cpu.f, rho=cpu.rho, ux=cpu.ux, uy=cpu.uy)
    checkpoints = {1, 2, 12, 20, 100, 300, 500, 501, steps}
    records = []
    started = time.perf_counter()
    for i in range(1, steps + 1):
        cpu.step()
        gpu.step()
        if i in checkpoints:
            records.append(compare(cpu, gpu, 2e-12))
            print(f"{gpu.backend} N{grid}x{config.grid.NY} Re{re}: step {i}, max field error "
                  f"{max(records[-1][k] for k in ('f', 'rho', 'ux', 'uy')):.3e}", flush=True)
        if cpu.stop_reason != "running":
            break
    return dict(grid=[grid, config.grid.NY], Re=re, random_state=random_state,
                checks=records, seconds=time.perf_counter() - started)


def protection_and_stop_tests(solver_type):
    results = []
    for mode, expected in (("nan", "Non-finite population or macroscopic field"),
                           ("density", "Non-positive density"),
                           ("mach", "Actual maximum Mach exceeded configured limit")):
        cfg = make_config(grid=16, re=100)
        cpu, gpu = CPUSolver(cfg), solver_type(cfg)
        if mode == "nan":
            cpu.f[2, 3, 0] = np.nan
        elif mode == "density":
            cpu.rho[2, 3] = -1.0
        else:
            cpu.ux[2, 3] = 0.2
        gpu.load_state(f=cpu.f, rho=cpu.rho, ux=cpu.ux, uy=cpu.uy)
        cpu.step()
        gpu.step()
        assert cpu.iteration == gpu.iteration == 0
        assert cpu.stop_reason == gpu.stop_reason == "diverged"
        assert cpu._failure == gpu._failure == expected
        results.append(mode + "_pre_step_protection")
    # Failure generated by an actual update must be caught at that step.
    cfg = make_config(grid=16, re=100, ramp_steps=0)
    cfg.boundaries["top"].ux = 0.08
    cpu, gpu = CPUSolver(cfg), solver_type(cfg)
    cpu.step()
    gpu.step()
    assert cpu.iteration == gpu.iteration == 1
    assert cpu.stop_reason == gpu.stop_reason == "diverged"
    assert cpu._failure == gpu._failure == "Actual maximum Mach exceeded configured limit"
    results.append("mach_post_step_protection")
    for strict in (False, True):
        cfg = make_config(grid=16, re=100, min_iter=5, ramp_steps=7)
        cfg.boundaries["top"].ux = 0
        cfg.convergence.consecutive_reports = 2
        cfg.convergence.mass_criterion = strict
        cpu, gpu = CPUSolver(cfg), solver_type(cfg)
        cpu.mass0 *= 1.01
        gpu.host.mass0 *= 1.01
        for i in range(1, 11):
            cpu.step()
            gpu.step()
            assert cpu.stop_reason == gpu.stop_reason
            if i < 8 or strict:
                assert gpu.stop_reason == "running"
            else:
                assert gpu.stop_reason == "converged" and gpu.iteration == 8
                break
        results.append("strict_mass_blocks" if strict else "zero_residual_minimum_ramp_consecutive")
    cfg = make_config(grid=16, re=100, max_iter=300, report_interval=100)
    cpu, gpu = CPUSolver(cfg), solver_type(cfg)
    cpu_reports = [(r.iteration, r.stop_reason) for r in cpu.run()]
    gpu_reports = [(r.iteration, r.stop_reason) for r in gpu.run()]
    assert cpu_reports == gpu_reports
    assert gpu_reports[-1] == (300, "max_iter")
    results.append("budget_and_report_schedule")
    cfg.flow.body_force_x = 1e-6
    try:
        solver_type(cfg)
    except ValueError:
        results.append("unsupported_force_rejected")
    else:
        raise AssertionError("Unsupported force was silently accepted")
    print("Protection/stop tests passed: " + ", ".join(results), flush=True)
    return results


def low_re_convergence(solver_type):
    cfg = make_config(grid=64, re=100, max_iter=50000)
    cpu, gpu = CPUSolver(cfg), solver_type(cfg)
    checks = []
    start = time.perf_counter()
    for i in range(1, 50001):
        cpu.step()
        gpu.step()
        if i == 1 or i % 200 == 0 or cpu.stop_reason != "running" or gpu.stop_reason != "running":
            cpu.report()
            gpu.report()
        if i in (1, 500, 2000, 5000, 10000, 15000) or cpu.stop_reason != "running" or gpu.stop_reason != "running":
            checks.append(compare(cpu, gpu, 5e-11))
            print(f"{gpu.backend} N64 Re100: step {i}, residual={gpu.decision_residual:.12g}, "
                  f"elapsed={time.perf_counter()-start:.1f}s", flush=True)
        if cpu.stop_reason != "running" or gpu.stop_reason != "running":
            break
    assert cpu.stop_reason == gpu.stop_reason == "converged"
    assert cpu.iteration == gpu.iteration == 16148
    with np.load(REFERENCE / "historical_Re100_N64/results.npz", allow_pickle=False) as historical:
        old_differences = {k: float(np.max(np.abs(getattr(cpu, k) - historical[k])))
                           for k in ("rho", "ux", "uy")}
        assert max(old_differences.values()) < 1e-12
    np.savez_compressed(ROOT / f"validation/{gpu.backend}_N64_Re100.npz",
                        cpu_rho=cpu.rho, cpu_ux=cpu.ux, cpu_uy=cpu.uy,
                        gpu_rho=cp.asnumpy(gpu.rho), gpu_ux=cp.asnumpy(gpu.ux), gpu_uy=cp.asnumpy(gpu.uy))
    return dict(passed=True, checks=checks, iterations=gpu.iteration, stop_reason=gpu.stop_reason,
                cpu_diagnostics=cpu.history[-1], gpu_diagnostics=gpu.history[-1],
                cpu_vs_historical=old_differences, seconds=time.perf_counter() - start)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--backend", choices=("array", "fused"), default="array")
    parser.add_argument("--full", action="store_true")
    args = parser.parse_args()
    solver_type = ArrayGPUSolver
    if args.backend == "fused":
        from gpu_fused import FusedGPUSolver
        solver_type = FusedGPUSolver
    result = dict(started_at=dt.datetime.now().astimezone().isoformat(), backend=args.backend,
                  passed=False, frozen_sources_verified=verify_reference(),
                  tolerances=dict(short_field_atol=2e-12, long_field_atol=5e-11,
                                  residual_atol=5e-12, residual_rtol=5e-8),
                  source_sha256=source_fingerprints(), trajectories=[])
    path = ROOT / f"validation/correctness_{args.backend}.json"
    def save():
        path.write_text(json.dumps(result, indent=2, allow_nan=False), encoding="utf-8")
    save()
    try:
        for case in ((16, 100, 1000, False), (17, 100, 20, True), (256, 5468, 1000, False)):
            result["trajectories"].append(trajectory(solver_type, *case))
            save()
        result["protection_tests"] = protection_and_stop_tests(solver_type)
        save()
        if args.full:
            result["low_re"] = low_re_convergence(solver_type)
        result["passed"] = True
        result["completed_at"] = dt.datetime.now().astimezone().isoformat()
    except Exception as exc:
        result["error"] = repr(exc)
        raise
    finally:
        save()
    print("PASS: " + str(path), flush=True)


if __name__ == "__main__":
    main()
